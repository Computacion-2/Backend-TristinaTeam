SET DEFINE OFF;
SET SERVEROUTPUT ON;

-- ---------------------------------------------------------------------------
-- 1. SEGURIDAD: USUARIOS, ROLES Y PERMISOS
-- ---------------------------------------------------------------------------

CREATE TABLE app_user (
    user_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    email            VARCHAR2(160) NOT NULL,
    password_hash    VARCHAR2(255) NOT NULL,
    account_status   VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_user_status CHECK (account_status IN
        ('ACTIVE', 'INACTIVE', 'SUSPENDED', 'DELETED'))
);

CREATE TABLE app_role (
    role_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    role_name        VARCHAR2(60) NOT NULL,
    description      VARCHAR2(300),
    active_flag      CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_app_role PRIMARY KEY (role_id),
    CONSTRAINT uq_app_role_name UNIQUE (role_name),
    CONSTRAINT ck_role_active CHECK (active_flag IN ('Y', 'N'))
);

CREATE TABLE app_permission (
    permission_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    permission_code  VARCHAR2(100) NOT NULL,
    permission_name  VARCHAR2(120) NOT NULL,
    description      VARCHAR2(300),
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_app_permission PRIMARY KEY (permission_id),
    CONSTRAINT uq_permission_code UNIQUE (permission_code)
);

CREATE TABLE user_role (
    user_id          NUMBER NOT NULL,
    role_id          NUMBER NOT NULL,
    assigned_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    assigned_by      NUMBER,
    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_ur_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_ur_role FOREIGN KEY (role_id)
        REFERENCES app_role (role_id) ON DELETE CASCADE,
    CONSTRAINT fk_ur_assigned_by FOREIGN KEY (assigned_by)
        REFERENCES app_user (user_id)
);

CREATE TABLE role_permission (
    role_id          NUMBER NOT NULL,
    permission_id    NUMBER NOT NULL,
    granted_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_role_permission PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_rp_role FOREIGN KEY (role_id)
        REFERENCES app_role (role_id) ON DELETE CASCADE,
    CONSTRAINT fk_rp_permission FOREIGN KEY (permission_id)
        REFERENCES app_permission (permission_id) ON DELETE CASCADE
);

CREATE TABLE user_profile (
    user_id              NUMBER NOT NULL,
    full_name            VARCHAR2(140) NOT NULL,
    photo_url            VARCHAR2(500),
    phone_number         VARCHAR2(30),
    city                 VARCHAR2(100),
    academic_program     VARCHAR2(140),
    emergency_contact    VARCHAR2(140),
    emergency_phone      VARCHAR2(30),
    profile_updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_user_profile PRIMARY KEY (user_id),
    CONSTRAINT fk_profile_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- 2. CATALOGOS Y PERFILES DE MASCOTAS/CUIDADORES
-- ---------------------------------------------------------------------------

CREATE TABLE service_type (
    service_type_id  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    service_name     VARCHAR2(100) NOT NULL,
    description      VARCHAR2(400),
    active_flag      CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_service_type PRIMARY KEY (service_type_id),
    CONSTRAINT uq_service_name UNIQUE (service_name),
    CONSTRAINT ck_service_active CHECK (active_flag IN ('Y', 'N'))
);

CREATE TABLE pet_species (
    species_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    species_name     VARCHAR2(80) NOT NULL,
    active_flag      CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT pk_pet_species PRIMARY KEY (species_id),
    CONSTRAINT uq_species_name UNIQUE (species_name),
    CONSTRAINT ck_species_active CHECK (active_flag IN ('Y', 'N'))
);

-- Catálogo cerrado de los estados permitidos para una reserva.
CREATE TABLE booking_status (
    status_code       VARCHAR2(30) NOT NULL,
    status_name       VARCHAR2(80) NOT NULL,
    CONSTRAINT pk_booking_status PRIMARY KEY (status_code),
    CONSTRAINT uq_booking_status_name UNIQUE (status_name),
    CONSTRAINT ck_booking_status_code CHECK (status_code IN
        ('SCHEDULED', 'IN_PROGRESS', 'PENDING_CONFIRMATION',
         'COMPLETED', 'CANCELLED'))
);

CREATE TABLE pet (
    pet_id               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    owner_id             NUMBER NOT NULL,
    species_id           NUMBER NOT NULL,
    pet_name             VARCHAR2(100) NOT NULL,
    breed                VARCHAR2(100),
    birth_date           DATE,
    sex                  VARCHAR2(12),
    weight_kg            NUMBER(6,2),
    temperament          VARCHAR2(500),
    care_instructions    VARCHAR2(1000),
    medical_alerts       VARCHAR2(1000),
    pet_status           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_pet PRIMARY KEY (pet_id),
    CONSTRAINT fk_pet_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (user_id),
    CONSTRAINT fk_pet_species FOREIGN KEY (species_id)
        REFERENCES pet_species (species_id),
    CONSTRAINT ck_pet_sex CHECK (sex IS NULL OR sex IN
        ('FEMALE', 'MALE', 'UNKNOWN')),
    CONSTRAINT ck_pet_weight CHECK (weight_kg IS NULL OR weight_kg > 0),
    CONSTRAINT ck_pet_status CHECK (pet_status IN
        ('ACTIVE', 'ARCHIVED', 'DELETED'))
);

CREATE TABLE pet_photo (
    pet_photo_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    pet_id           NUMBER NOT NULL,
    photo_url        VARCHAR2(500) NOT NULL,
    main_photo_flag  CHAR(1) DEFAULT 'N' NOT NULL,
    uploaded_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_pet_photo PRIMARY KEY (pet_photo_id),
    CONSTRAINT fk_pet_photo_pet FOREIGN KEY (pet_id)
        REFERENCES pet (pet_id) ON DELETE CASCADE,
    CONSTRAINT uq_pet_photo UNIQUE (pet_id, photo_url),
    CONSTRAINT ck_main_photo CHECK (main_photo_flag IN ('Y', 'N'))
);

CREATE TABLE caregiver_profile (
    caregiver_id        NUMBER NOT NULL,
    biography           VARCHAR2(1200) NOT NULL,
    experience_years    NUMBER(3) DEFAULT 0 NOT NULL,
    service_city        VARCHAR2(100) NOT NULL,
    service_zone        VARCHAR2(160),
    active_flag         CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_caregiver_profile PRIMARY KEY (caregiver_id),
    CONSTRAINT fk_caregiver_user FOREIGN KEY (caregiver_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_care_exp CHECK (experience_years >= 0),
    CONSTRAINT ck_care_active CHECK (active_flag IN ('Y', 'N'))
);

CREATE TABLE caregiver_service (
    caregiver_id        NUMBER NOT NULL,
    service_type_id     NUMBER NOT NULL,
    base_rate           NUMBER(12,2) NOT NULL,
    active_flag         CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT pk_caregiver_service PRIMARY KEY
        (caregiver_id, service_type_id),
    CONSTRAINT fk_cs_caregiver FOREIGN KEY (caregiver_id)
        REFERENCES caregiver_profile (caregiver_id) ON DELETE CASCADE,
    CONSTRAINT fk_cs_service FOREIGN KEY (service_type_id)
        REFERENCES service_type (service_type_id),
    CONSTRAINT ck_cs_rate CHECK (base_rate > 0),
    CONSTRAINT ck_cs_active CHECK (active_flag IN ('Y', 'N'))
);

CREATE TABLE caregiver_availability (
    availability_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    caregiver_id       NUMBER NOT NULL,
    day_of_week        NUMBER(1) NOT NULL,
    start_time         VARCHAR2(5) NOT NULL,
    end_time           VARCHAR2(5) NOT NULL,
    valid_from         DATE,
    valid_until        DATE,
    active_flag        CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT pk_care_availability PRIMARY KEY (availability_id),
    CONSTRAINT fk_ca_caregiver FOREIGN KEY (caregiver_id)
        REFERENCES caregiver_profile (caregiver_id) ON DELETE CASCADE,
    CONSTRAINT ck_ca_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_ca_active CHECK (active_flag IN ('Y', 'N')),
    CONSTRAINT ck_ca_dates CHECK
        (valid_until IS NULL OR valid_from IS NULL OR valid_until >= valid_from)
);

-- ---------------------------------------------------------------------------
-- 3. SOLICITUDES, POSTULACIONES Y RESERVAS DE CUIDADO
-- ---------------------------------------------------------------------------

CREATE TABLE care_request (
    request_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    owner_id            NUMBER NOT NULL,
    pet_id              NUMBER NOT NULL,
    service_type_id     NUMBER NOT NULL,
    start_at            TIMESTAMP NOT NULL,
    end_at              TIMESTAMP NOT NULL,
    city                VARCHAR2(100) NOT NULL,
    zone_name           VARCHAR2(160),
    address_reference   VARCHAR2(500),
    request_notes       VARCHAR2(1500),
    max_budget          NUMBER(12,2),
    request_status      VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    cancellation_reason VARCHAR2(500),
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_care_request PRIMARY KEY (request_id),
    CONSTRAINT fk_cr_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (user_id),
    CONSTRAINT fk_cr_pet FOREIGN KEY (pet_id)
        REFERENCES pet (pet_id),
    CONSTRAINT fk_cr_service FOREIGN KEY (service_type_id)
        REFERENCES service_type (service_type_id),
    CONSTRAINT ck_cr_dates CHECK (end_at > start_at),
    CONSTRAINT ck_cr_budget CHECK (max_budget IS NULL OR max_budget > 0),
    CONSTRAINT ck_cr_status CHECK (request_status IN
        ('OPEN', 'ASSIGNED', 'CANCELLED', 'CLOSED'))
);

CREATE TABLE care_application (
    application_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    request_id          NUMBER NOT NULL,
    caregiver_id        NUMBER NOT NULL,
    proposed_rate       NUMBER(12,2) NOT NULL,
    application_message VARCHAR2(1000),
    application_status  VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    response_reason     VARCHAR2(500),
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_care_application PRIMARY KEY (application_id),
    CONSTRAINT fk_cap_request FOREIGN KEY (request_id)
        REFERENCES care_request (request_id) ON DELETE CASCADE,
    CONSTRAINT fk_cap_caregiver FOREIGN KEY (caregiver_id)
        REFERENCES caregiver_profile (caregiver_id),
    CONSTRAINT uq_application UNIQUE (request_id, caregiver_id),
    CONSTRAINT ck_cap_rate CHECK (proposed_rate > 0),
    CONSTRAINT ck_cap_status CHECK (application_status IN
        ('PENDING', 'ACCEPTED', 'REJECTED', 'WITHDRAWN'))
);

CREATE TABLE care_booking (
    booking_id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    request_id              NUMBER NOT NULL,
    accepted_application_id NUMBER NOT NULL,
    owner_id                NUMBER NOT NULL,
    caregiver_id            NUMBER NOT NULL,
    agreed_rate             NUMBER(12,2) NOT NULL,
    exact_address           VARCHAR2(500) NOT NULL,
    booking_status_code     VARCHAR2(30) DEFAULT 'SCHEDULED' NOT NULL,
    owner_confirmed_flag    CHAR(1) DEFAULT 'N' NOT NULL,
    caregiver_done_flag     CHAR(1) DEFAULT 'N' NOT NULL,
    cancellation_reason     VARCHAR2(500),
    accepted_at             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    started_at              TIMESTAMP,
    completed_at            TIMESTAMP,
    cancelled_at            TIMESTAMP,
    CONSTRAINT pk_care_booking PRIMARY KEY (booking_id),
    CONSTRAINT fk_cb_request FOREIGN KEY (request_id)
        REFERENCES care_request (request_id),
    CONSTRAINT fk_cb_application FOREIGN KEY (accepted_application_id)
        REFERENCES care_application (application_id),
    CONSTRAINT fk_cb_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (user_id),
    CONSTRAINT fk_cb_caregiver FOREIGN KEY (caregiver_id)
        REFERENCES caregiver_profile (caregiver_id),
    CONSTRAINT fk_cb_status FOREIGN KEY (booking_status_code)
        REFERENCES booking_status (status_code),
    CONSTRAINT uq_cb_booking_context UNIQUE (booking_id, request_id),
    CONSTRAINT uq_booking_request UNIQUE (request_id),
    CONSTRAINT uq_booking_application UNIQUE (accepted_application_id),
    CONSTRAINT ck_cb_rate CHECK (agreed_rate > 0),
    CONSTRAINT ck_cb_owner_conf CHECK (owner_confirmed_flag IN ('Y', 'N')),
    CONSTRAINT ck_cb_care_done CHECK (caregiver_done_flag IN ('Y', 'N')),
    CONSTRAINT ck_cb_people CHECK (owner_id <> caregiver_id)
);

-- ---------------------------------------------------------------------------
-- 4. SEGUIMIENTO, REPUTACION, FAVORITOS, MODERACION Y NOTIFICACIONES
-- ---------------------------------------------------------------------------

CREATE TABLE care_update (
    update_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    booking_id         NUMBER NOT NULL,
    caregiver_id       NUMBER NOT NULL,
    update_message     VARCHAR2(1200) NOT NULL,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_care_update PRIMARY KEY (update_id),
    CONSTRAINT fk_cu_booking FOREIGN KEY (booking_id)
        REFERENCES care_booking (booking_id) ON DELETE CASCADE,
    CONSTRAINT fk_cu_caregiver FOREIGN KEY (caregiver_id)
        REFERENCES caregiver_profile (caregiver_id)
);

CREATE TABLE care_update_photo (
    update_photo_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    update_id          NUMBER NOT NULL,
    photo_url          VARCHAR2(500) NOT NULL,
    uploaded_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_update_photo PRIMARY KEY (update_photo_id),
    CONSTRAINT fk_cup_update FOREIGN KEY (update_id)
        REFERENCES care_update (update_id) ON DELETE CASCADE
);

CREATE TABLE user_review (
    review_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    booking_id         NUMBER NOT NULL,
    reviewer_id        NUMBER NOT NULL,
    reviewed_user_id   NUMBER NOT NULL,
    rating             NUMBER(1) NOT NULL,
    review_comment     VARCHAR2(1000),
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_user_review PRIMARY KEY (review_id),
    CONSTRAINT fk_review_booking FOREIGN KEY (booking_id)
        REFERENCES care_booking (booking_id) ON DELETE CASCADE,
    CONSTRAINT fk_review_author FOREIGN KEY (reviewer_id)
        REFERENCES app_user (user_id),
    CONSTRAINT fk_review_target FOREIGN KEY (reviewed_user_id)
        REFERENCES app_user (user_id),
    CONSTRAINT uq_review_author UNIQUE (booking_id, reviewer_id),
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_review_people CHECK (reviewer_id <> reviewed_user_id)
);

CREATE TABLE favorite_caregiver (
    owner_id           NUMBER NOT NULL,
    caregiver_id       NUMBER NOT NULL,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_favorite_caregiver PRIMARY KEY (owner_id, caregiver_id),
    CONSTRAINT fk_fc_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_fc_caregiver FOREIGN KEY (caregiver_id)
        REFERENCES caregiver_profile (caregiver_id) ON DELETE CASCADE,
    CONSTRAINT ck_fc_people CHECK (owner_id <> caregiver_id)
);

CREATE TABLE incident_report (
    report_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    reporter_id        NUMBER NOT NULL,
    reported_user_id   NUMBER NOT NULL,
    request_id         NUMBER NOT NULL,
    booking_id         NUMBER,
    report_reason      VARCHAR2(200) NOT NULL,
    report_details     VARCHAR2(2000) NOT NULL,
    evidence_url       VARCHAR2(500),
    report_status      VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    resolution_notes   VARCHAR2(1500),
    resolved_by        NUMBER,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    resolved_at        TIMESTAMP,
    CONSTRAINT pk_incident_report PRIMARY KEY (report_id),
    CONSTRAINT fk_ir_reporter FOREIGN KEY (reporter_id)
        REFERENCES app_user (user_id),
    CONSTRAINT fk_ir_reported FOREIGN KEY (reported_user_id)
        REFERENCES app_user (user_id),
    CONSTRAINT fk_ir_request FOREIGN KEY (request_id)
        REFERENCES care_request (request_id),
    CONSTRAINT fk_ir_booking FOREIGN KEY (booking_id, request_id)
        REFERENCES care_booking (booking_id, request_id),
    CONSTRAINT fk_ir_admin FOREIGN KEY (resolved_by)
        REFERENCES app_user (user_id),
    CONSTRAINT ck_ir_status CHECK (report_status IN
        ('OPEN', 'IN_REVIEW', 'RESOLVED', 'DISMISSED')),
    CONSTRAINT ck_ir_people CHECK (reporter_id <> reported_user_id)
);

CREATE TABLE app_notification (
    notification_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id           NUMBER NOT NULL,
    notification_type VARCHAR2(60) NOT NULL,
    title              VARCHAR2(180) NOT NULL,
    message_text       VARCHAR2(1000) NOT NULL,
    reference_entity   VARCHAR2(60),
    reference_id       NUMBER,
    read_flag          CHAR(1) DEFAULT 'N' NOT NULL,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    read_at            TIMESTAMP,
    CONSTRAINT pk_app_notification PRIMARY KEY (notification_id),
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_notification_read CHECK (read_flag IN ('Y', 'N'))
);

